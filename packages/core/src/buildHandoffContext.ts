import { getAgent } from './agents'
import type { ProjectWorkspace } from './service'
import type { AgentType, ContextCategory, ProjectTask } from './types'
import { CHANGE_LABEL, CONTEXT_CATEGORIES, CRITERION_LABEL, PROJECT_STATUS_LABEL, VERIFICATION_LABEL } from './labels'

/** Rough heuristic: about four characters per token for English and code. Not a tokenizer. */
const CHARS_PER_TOKEN_ESTIMATE = 4

export interface HandoffContextInput {
  workspace: ProjectWorkspace
  taskId: string
  sourceAgent: AgentType
  targetAgent: AgentType
  includedContext: readonly ContextCategory[]
}

export interface HandoffSection {
  category: ContextCategory
  title: string
  items: string[]
}

export interface HandoffContext {
  task: ProjectTask
  sections: HandoffSection[]
  text: string
  estimatedTokens: number
}

type SectionBuilder = (workspace: ProjectWorkspace, task: ProjectTask) => string[]

const SECTION_BUILDERS: Record<ContextCategory, SectionBuilder> = {
  'project-overview': ({ project }) => [
    `${project.name}: ${project.description}`,
    `Repository ${project.repositoryName}, branch ${project.branch}`,
    `Stack: ${project.stack.join(', ')}`,
  ],
  'current-task': (_, task) => [
    `${task.title} (${PROJECT_STATUS_LABEL[task.status]})`,
    `Objective: ${task.objective}`,
    ...task.acceptanceCriteria.map((c) => `[${CRITERION_LABEL[c.status]}] ${c.text}`),
    ...task.completedSteps.map((step) => `Done: ${step}`),
  ],
  'file-changes': ({ files }, task) =>
    files
      .filter((file) => task.relatedFileIds.includes(file.id))
      .map((file) => `${file.path} (${CHANGE_LABEL[file.changeType].toLowerCase()}): ${file.summary}`),
  decisions: ({ memory }, task) =>
    memory.filter((m) => m.kind === 'decision' && m.taskId === task.id).map((m) => `${m.title} Source: ${m.sourceDetail}.`),
  'previous-attempts': ({ memory }, task) =>
    memory
      .filter((m) => (m.kind === 'previous-attempt' || m.kind === 'known-issue') && m.taskId === task.id)
      .map((m) => `${m.title} ${m.body}`),
  verification: ({ verification }, task) =>
    verification
      .filter((v) => task.verificationIds.includes(v.id))
      .map((v) => `${v.name} — ${VERIFICATION_LABEL[v.status]}. ${v.detail} (\`${v.command}\`)`),
  'next-steps': (_, task) => [
    ...(task.nextAction ? [`Recommended next action: ${task.nextAction}`] : []),
    ...task.remainingSteps.map((step) => `Remaining: ${step}`),
  ],
}

function renderText(input: HandoffContextInput, task: ProjectTask, sections: HandoffSection[]): string {
  const header = [
    '# Continuum handoff context',
    `Project: ${input.workspace.project.name}`,
    `Task: ${task.title}`,
    `From: ${getAgent(input.sourceAgent).name} → To: ${getAgent(input.targetAgent).name}`,
    '',
    '> Generated by the Continuum demo from mock data. Verify against the repository before acting.',
  ]
  const body = sections.flatMap((section) => [
    '',
    `## ${section.title}`,
    ...(section.items.length > 0 ? section.items.map((item) => `- ${item}`) : ['- None recorded.']),
  ])
  return [...header, ...body].join('\n')
}

export function buildHandoffContext(input: HandoffContextInput): HandoffContext {
  const task = input.workspace.tasks.find((candidate) => candidate.id === input.taskId)
  if (!task) throw new Error(`Task "${input.taskId}" is not part of project "${input.workspace.project.id}".`)

  // Keep a stable, logical order regardless of the order categories were selected in.
  const sections = CONTEXT_CATEGORIES.filter((category) => input.includedContext.includes(category.id)).map((category) => ({
    category: category.id,
    title: category.label,
    items: SECTION_BUILDERS[category.id](input.workspace, task),
  }))
  const text = renderText(input, task, sections)

  return { task, sections, text, estimatedTokens: Math.ceil(text.length / CHARS_PER_TOKEN_ESTIMATE) }
}
